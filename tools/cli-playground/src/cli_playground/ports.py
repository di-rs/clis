"""Synchronous storage ports and the application boundary that schedules their I/O."""

from collections.abc import Awaitable, Callable
from typing import Protocol
from uuid import UUID

from cli_playground.domain import CreateIntent, SessionBinding, UploadIntent
from cli_playground.models import (
    ArtifactMetadata,
    BuildIdentity,
    BuildUpdate,
    Environment,
    EnvironmentMetadata,
    PreviewRecord,
)
from cli_playground.sandbox import SandboxView


class PersistenceUnavailable(RuntimeError):
    """Persistence failed; callers must not interpret failure as absent state."""


class EnvironmentStore(Protocol):
    def collect_artifacts(self) -> None: ...

    @staticmethod
    def identifier(pr: int) -> str: ...

    def is_closed(self, pr: int) -> bool: ...

    def close_pull_request(self, pr: int) -> None: ...

    def reopen_pull_request(self, pr: int) -> None: ...

    def record(
        self, identifier: str, *, include_inactive: bool = False
    ) -> PreviewRecord | None: ...

    def get(self, identifier: str, *, include_inactive: bool = False) -> Environment | None: ...

    def metadata(self, identifier: str) -> EnvironmentMetadata | None: ...

    def inactive_identifiers(self) -> set[str]: ...

    def remove(self, identifiers: set[str]) -> int: ...

    def for_pull_request(self, pr: int) -> set[str]: ...

    def check_build(self, pr: int, build: BuildIdentity | None) -> PreviewRecord | None: ...

    def update_build(self, pr: int, update: BuildUpdate) -> EnvironmentMetadata: ...

    def revisions(self) -> list[ArtifactMetadata]: ...

    def revision(self, pr: int, revision: str) -> ArtifactMetadata | None: ...

    def publish(self, artifact: ArtifactMetadata, build: BuildIdentity | None) -> Environment: ...

    def finish_upload(
        self, artifact: ArtifactMetadata, build: BuildIdentity | None
    ) -> Environment: ...


class SessionStore(Protocol):
    def recover_creation(self, intent: CreateIntent, sandbox: SandboxView) -> None: ...

    def save(self, binding: SessionBinding) -> None: ...

    def change(
        self, identifier: UUID, change: Callable[[SessionBinding], None], *, claimed: bool = False
    ) -> SessionBinding | None: ...

    def bindings(self) -> list[SessionBinding]: ...

    def get(self, identifier: UUID) -> SessionBinding | None: ...

    def create_intent(self, intent: CreateIntent) -> None: ...

    def creates(self) -> list[CreateIntent]: ...

    def claimed(self, identifier: UUID) -> None: ...

    def upload_intent(self, intent: UploadIntent) -> None: ...

    def uploads(self) -> list[UploadIntent]: ...

    def retire(self, identifier: UUID) -> None: ...

    def retirements(self) -> list[UUID]: ...

    def retired(self, identifier: UUID) -> None: ...

    def stop_environments(self, identifiers: set[str]) -> None: ...


class StoreRunner[Store](Protocol):
    def __call__[Result](self, operation: Callable[[Store], Result]) -> Awaitable[Result]: ...
