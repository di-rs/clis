"""Async persistence contracts; domain values and decisions remain synchronous."""

from collections.abc import Callable
from typing import Protocol
from uuid import UUID

from cli_playground.domain import CreateIntent, SessionBinding, UploadIntent
from cli_playground.models import (
    ArtifactMetadata,
    BuildIdentity,
    BuildUpdate,
    Environment,
    EnvironmentMetadata,
    PreviewRecord,
)
from cli_playground.sandbox import SandboxView


class PersistenceUnavailable(RuntimeError):
    """Persistence failed; callers must not interpret failure as absent state."""


class EnvironmentStore(Protocol):
    async def collect_artifacts(self) -> None: ...

    @staticmethod
    def identifier(pr: int) -> str: ...

    async def is_closed(self, pr: int) -> bool: ...

    async def close_pull_request(self, pr: int) -> None: ...

    async def reopen_pull_request(self, pr: int) -> None: ...

    async def record(
        self, identifier: str, *, include_inactive: bool = False
    ) -> PreviewRecord | None: ...

    async def get(
        self, identifier: str, *, include_inactive: bool = False
    ) -> Environment | None: ...

    async def metadata(self, identifier: str) -> EnvironmentMetadata | None: ...

    async def inactive_identifiers(self) -> set[str]: ...

    async def remove(self, identifiers: set[str]) -> int: ...

    async def check_build(self, pr: int, build: BuildIdentity | None) -> PreviewRecord | None: ...

    async def update_build(self, pr: int, update: BuildUpdate) -> EnvironmentMetadata: ...

    async def revision(self, pr: int, revision: str) -> ArtifactMetadata | None: ...

    async def publish(
        self, artifact: ArtifactMetadata, build: BuildIdentity | None
    ) -> Environment: ...

    async def finish_upload(
        self, artifact: ArtifactMetadata, build: BuildIdentity | None
    ) -> Environment: ...


class SessionStore(Protocol):
    async def recover_creation(self, intent: CreateIntent, sandbox: SandboxView) -> None: ...

    async def save(self, binding: SessionBinding) -> None: ...

    async def change(
        self, identifier: UUID, change: Callable[[SessionBinding], None], *, claimed: bool = False
    ) -> SessionBinding | None: ...

    async def bindings(self) -> list[SessionBinding]: ...

    async def pending_stops(self) -> list[SessionBinding]: ...

    async def pending_attachments(self, *, before: float | None = None) -> list[SessionBinding]: ...

    async def get(self, identifier: UUID) -> SessionBinding | None: ...

    async def create_intent(self, intent: CreateIntent) -> None: ...

    async def creates(self) -> list[CreateIntent]: ...

    async def claimed(self, identifier: UUID) -> None: ...

    async def upload_intent(self, intent: UploadIntent) -> None: ...

    async def uploads(self) -> list[UploadIntent]: ...

    async def retire(self, identifier: UUID) -> None: ...

    async def retirements(self) -> list[UUID]: ...

    async def retired(self, identifier: UUID) -> None: ...

    async def stop_environments(self, identifiers: set[str]) -> None: ...
